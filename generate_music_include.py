#!/usr/bin/env python3
"""Pack all canonical FYM streams into compressed Pascal byte arrays."""

from pathlib import Path


ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "assets" / "music_theme.inc"
TRACKS = (
    ("MUSIC_THEME_FYM_APL", "flob_theme"),
    ("MUSIC_WORLD_00_FYM_APL", "flob_world_00"),
    ("MUSIC_WORLD_01_FYM_APL", "flob_world_01"),
    ("MUSIC_WORLD_02_FYM_APL", "flob_world_02"),
    ("MUSIC_WORLD_03_FYM_APL", "flob_world_03"),
    ("MUSIC_WORLD_04_FYM_APL", "flob_world_04"),
    ("MUSIC_INTRO_FYM_APL", "flob_intro"),
    ("MUSIC_OUTRO_FYM_APL", "flob_outro"),
    ("MUSIC_ENDGAME_FYM_APL", "flob_endgame"),
)


def main() -> None:
    lines = [
        "{ generated by generate_music_include.py; do not edit }",
        "const",
    ]
    max_unpacked = 0
    total_packed = 0
    for name, stem in TRACKS:
        fym_path = ROOT / "audio" / "ym_music" / f"{stem}.fym"
        apl_path = fym_path.with_suffix(".fym.apl")
        fym = fym_path.read_bytes()
        data = apl_path.read_bytes()
        if len(fym) < 16 or fym[:4] != b"FYM1":
            raise RuntimeError(f"{fym_path}: expected an FYM1 stream")
        max_unpacked = max(max_unpacked, len(fym))
        total_packed += len(data)
        lines.append(f"    {name}: array[0..{len(data) - 1}] of byte = (")
        for offset in range(0, len(data), 15):
            chunk = data[offset : offset + 15]
            suffix = "," if offset + len(chunk) < len(data) else ""
            lines.append(
                "        " + ",".join(f"${value:02X}" for value in chunk) + suffix
            )
        lines.append("    );")
    lines.insert(2, f"    MUSIC_BUFFER_BYTES = {max_unpacked};")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(
        f"Wrote {OUTPUT}: {len(TRACKS)} tracks, "
        f"{total_packed} packed bytes, {max_unpacked}-byte buffer"
    )


if __name__ == "__main__":
    main()
