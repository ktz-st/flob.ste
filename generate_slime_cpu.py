"""Preshift canonical slime graphics and masks for an optional 68000 renderer."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def main():
    source = (ROOT / 'generated/sprite_assets_atlas/slime.inc').read_text()
    frames = [dict((k, int(v)) for k, v in re.findall(r'(\w+):(\d+)', record))
              for record in re.findall(r'\((widthPx:.*?)\)', source)]
    section = source.split('const SPR_SLIME_WORDS', 1)[1].split(');', 1)[0]
    words = [int(v, 16) for v in re.findall(r'\$([0-9A-Fa-f]+)', section)]
    table, assets = {}, {}
    for frame in frames:
        assert frame['rowWords'] == 1 and frame['heightPx'] == 6
        for shift in range(16):
            count = (shift + frame['widthPx'] + 15) // 16
            data = [count]
            for y in range(6):
                opacity = ((~words[frame['maskOffset'] + y] & 65535) << 16) >> shift
                gfx = [(words[frame['dataOffset'] + y * 4 + p] << 16) >> shift
                       for p in range(4)]
                for block in range(count):
                    bits = 16 if block == 0 else 0
                    mask = ~(opacity >> bits) & 65535
                    data += [mask, mask] + [(g >> bits) & (~mask & 65535) for g in gfx]
            key = tuple(data)
            if key not in assets:
                assets[key] = f'cpu_data_{len(assets)}'
            table[frame['paletteOffset'] + shift * 4] = assets[key]
    lines = ['; Generated by generate_slime_cpu.py; do not edit.',
             '        export DrawSlimeCPU', '        export _DrawSlimeCPU',
             '; cdecl: destination, dispatch byte offset (32-bit arguments).',
             'DrawSlimeCPU:', '_DrawSlimeCPU:',
             '        movea.l 4(sp),a1', '        move.l 8(sp),d0',
             '        lea cpu_table(pc),a0', '        movea.l (a0,d0.w),a0',
             '.wait:', '        btst #7,$ffff8a3c.w', '        bne.s .wait',
             '        cmpi.w #2,(a0)+', '        beq cpu_two']
    for count, label in ((1, 'cpu_one'), (2, 'cpu_two')):
        lines.append(label + ':')
        for y in range(6):
            for block in range(count):
                lines += ['        move.l (a0)+,d0']
                for pair in range(2):
                    off = y * 160 + block * 8 + pair * 4
                    lines += [f'        and.l d0,{off}(a1)',
                              '        move.l (a0)+,d1', f'        or.l d1,{off}(a1)']
        lines.append('        rts')
    lines += ['        even', 'cpu_table:']
    lines += [f'        dc.l {table.get(i, "0")}' for i in range(0, max(table) + 4, 4)]
    for data, label in assets.items():
        lines += [label + ':', '        dc.w ' + ','.join(f'${v:04x}' for v in data)]
    (ROOT / 'generated/slime_cpu.s').write_text('\n'.join(lines) + '\n')
    print(f'{len(table)} variants, {len(assets)} unique data blocks, '
          f'{sum(len(d) * 2 for d in assets)} data bytes')


if __name__ == '__main__':
    main()
