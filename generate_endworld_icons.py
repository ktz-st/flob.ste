#!/usr/bin/env python3
"""
Generate STE planar bitmap4 icons for the end-world summary screen.

Input assets are editable 32x40 indexed GIFs from the original Atari build.
Output bitmaps use the same raw ST-low interleaved bitplane layout as screen
memory, so they can be copied with BlitterCopyBitmap4.
"""

from __future__ import annotations

from pathlib import Path
from PIL import Image

FLOB_SRC = Path("/Users/kriss/GCC.ELF/flob")
FLOB_STE = Path("/Users/kriss/GCC.ELF/flob-ste")
ASSETS_SRC = FLOB_SRC / "assets"
OUT = FLOB_STE / "assets" / "endworld_icons.inc"

ICONS = {
    "END_ICON_BIGMAP": "bigmap.gif",
    "END_ICON_BIGVIAL": "bigvial.gif",
    "END_ICON_BIGFORMULA": "bigformula.gif",
    "END_ICON_SKULL": "skull.gif",
}

SRC_ICON_W = 32
SRC_ICON_H = 40
ICON_SCALE = 2
ICON_W = SRC_ICON_W * ICON_SCALE   # 64
ICON_H = SRC_ICON_H * ICON_SCALE   # 80


def ste_word_from_rgb(r: int, g: int, b: int) -> int:
    # Standard ST 3-bit palette component range 0..7.
    rr = (r * 7 + 127) // 255
    gg = (g * 7 + 127) // 255
    bb = (b * 7 + 127) // 255
    return (rr << 8) | (gg << 4) | bb


def gif_palette_words(path: Path) -> list[int]:
    im = Image.open(path)
    palette = im.getpalette() or []
    words: list[int] = []
    for i in range(16):
        base = i * 3
        if base + 2 < len(palette):
            words.append(ste_word_from_rgb(palette[base], palette[base + 1], palette[base + 2]))
        else:
            words.append(0)
    return words


def gif_to_st_bitmap4(path: Path) -> bytes:
    im = Image.open(path)
    if im.mode != "P":
        im = im.convert("P")
    if im.size != (SRC_ICON_W, SRC_ICON_H):
        raise RuntimeError(f"{path}: expected {SRC_ICON_W}x{SRC_ICON_H}, got {im.size}")

    im = im.resize((ICON_W, ICON_H), Image.Resampling.NEAREST)

    pixels = list(im.getdata())
    out = bytearray()
    for y in range(ICON_H):
        row = pixels[y * ICON_W : (y + 1) * ICON_W]
        for block_x in range(0, ICON_W, 16):
            for plane in range(4):
                word = 0
                for bit in range(16):
                    color = row[block_x + bit] & 15
                    if color & (1 << plane):
                        word |= 1 << (15 - bit)
                out.append((word >> 8) & 255)
                out.append(word & 255)
    return bytes(out)


def byte_array(name: str, data: bytes) -> str:
    vals = [f"${b:02X}" for b in data]
    rows = []
    for i in range(0, len(vals), 16):
        rows.append("    " + ",".join(vals[i : i + 16]))
    return f"const {name}: array[0..{len(data) - 1}] of byte = (\n" + ",\n".join(rows) + "\n);\n"


def word_array(name: str, data: list[int]) -> str:
    vals = [f"${w:03X}" for w in data]
    rows = []
    for i in range(0, len(vals), 8):
        rows.append("    " + ",".join(vals[i : i + 8]))
    return f"const {name}: array[0..{len(data) - 1}] of word = (\n" + ",\n".join(rows) + "\n);\n"


def main() -> None:
    first_icon_path = ASSETS_SRC / next(iter(ICONS.values()))
    chunks = [
        "// Generated by generate_endworld_icons.py from flob/assets/*.gif",
        f"// Source GIFs are {SRC_ICON_W}x{SRC_ICON_H}; rendered at {ICON_SCALE}x ({ICON_W}x{ICON_H}).",
        f"const END_ICON_WIDTH = {ICON_W};",
        f"const END_ICON_HEIGHT = {ICON_H};",
        "",
        word_array("END_ICON_PAL", gif_palette_words(first_icon_path)),
    ]
    for const_name, filename in ICONS.items():
        chunks.append(byte_array(const_name, gif_to_st_bitmap4(ASSETS_SRC / filename)))
    OUT.write_text("\n".join(chunks))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
