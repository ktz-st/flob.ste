#!/usr/bin/env python3
"""Generate Apultra-compressed world data and per-room collision includes."""

from __future__ import annotations

import subprocess
import tempfile
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parent
SOURCE_ROOT = ROOT.parent / "flob" / "worlds"
ROOM_ROOT = ROOT / "game_rooms"
OUTPUT_ROOT = ROOT / "worlds"
WORLD_DATA_SIZE = 8192
COLLISION_SIZE = 3200

WORLD_DIRS = [
    "00_Escape_From_The_Lab",
    "01_Abominable_Sewers",
    "02_Suburbian_Parkour",
    "03_Hazardous_Mudlands",
    "04_Silver_Dust_Mines",
    "05_Return_To_The_Lab",
]


def compress_apultra(data: bytes) -> bytes:
    with tempfile.TemporaryDirectory() as temp_dir:
        raw_path = Path(temp_dir) / "input.bin"
        packed_path = Path(temp_dir) / "output.apl"
        raw_path.write_bytes(data)
        subprocess.run(
            ["apultra", str(raw_path), str(packed_path)],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        return packed_path.read_bytes()


def pascal_array(name: str, data: bytes) -> str:
    # Keep the following constant word-aligned for the 68000.
    if len(data) & 1:
        data += b"\0"
    rows = []
    values = [f"${value:02X}" for value in data]
    for offset in range(0, len(values), 15):
        rows.append("  " + ",".join(values[offset:offset + 15]))
    return (
        f"const {name} : array[0..{len(data) - 1}] of byte=(\n"
        + ",\n".join(rows)
        + ");\n"
    )


def collision_bytes(path: Path) -> bytes:
    image = Image.open(path)
    if image.mode != "P" or image.size != (160, 80):
        raise ValueError(f"{path}: collision must be indexed 160x80")
    pixels = [int(value) for value in image.getdata()]
    used = set(pixels)
    if not used.issubset({0, 1, 2, 3}):
        raise ValueError(f"{path}: collision indices outside 0..3: {sorted(used)}")

    packed = bytearray()
    for y in range(80):
        row = pixels[y * 160:(y + 1) * 160]
        for x in range(0, 160, 4):
            packed.append(
                (row[x] << 6)
                | (row[x + 1] << 4)
                | (row[x + 2] << 2)
                | row[x + 3]
            )
    if len(packed) != COLLISION_SIZE:
        raise AssertionError(f"{path}: packed collision size is {len(packed)}")
    return bytes(packed)


def generate_world(world_index: int, source_dir_name: str) -> tuple[int, int, int, int]:
    prefix = f"W{world_index:02d}"
    world_source = SOURCE_ROOT / source_dir_name / f"world_{world_index:02d}.bin"
    world_raw = world_source.read_bytes()
    if len(world_raw) != WORLD_DATA_SIZE:
        raise ValueError(f"{world_source}: expected {WORLD_DATA_SIZE} bytes")
    world_packed = compress_apultra(world_raw)
    (OUTPUT_ROOT / f"world_{world_index:02d}.inc").write_text(
        "// Generated by generate_world_data.py; do not edit.\n"
        + pascal_array(f"WORLD_{world_index:02d}_DATA_APL", world_packed)
    )

    collision_paths = sorted(
        (ROOM_ROOT / f"world_{world_index:02d}").glob(
            "room_[0-9][0-9]_collision.png"
        ),
        key=lambda path: int(path.stem.split("_")[1]),
    )
    expected_rooms = list(range(len(collision_paths)))
    room_numbers = [int(path.stem.split("_")[1]) for path in collision_paths]
    if room_numbers != expected_rooms:
        raise ValueError(
            f"world {world_index}: collision rooms must be contiguous 0..N: "
            f"{room_numbers}"
        )

    collision_parts = ["// Generated by generate_world_data.py; do not edit.\n"]
    collision_names = []
    collision_raw_total = 0
    collision_packed_total = 0
    for room_number, path in enumerate(collision_paths):
        raw = collision_bytes(path)
        packed = compress_apultra(raw)
        name = f"{prefix}_COL_{room_number:02d}_APL"
        collision_parts.append(pascal_array(name, packed))
        collision_parts.append("\n")
        collision_names.append(name)
        collision_raw_total += len(raw)
        collision_packed_total += len(packed)

    collision_parts.append(f"const {prefix}_COL_APL_COUNT = {len(collision_names)};\n")
    collision_parts.append(
        f"const {prefix}_COL_APL_PTRS: array[0..{len(collision_names) - 1}] of pointer=(\n"
    )
    for index, name in enumerate(collision_names):
        comma = "," if index + 1 < len(collision_names) else ""
        collision_parts.append(f"  @{name}[0]{comma}\n")
    collision_parts.append(");\n")
    (OUTPUT_ROOT / f"world_{world_index:02d}_collisions.inc").write_text(
        "".join(collision_parts)
    )
    return (
        len(world_raw),
        len(world_packed),
        collision_raw_total,
        collision_packed_total,
    )


def main() -> None:
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    world_raw_total = 0
    world_packed_total = 0
    collision_raw_total = 0
    collision_packed_total = 0

    for world_index, source_dir_name in enumerate(WORLD_DIRS):
        wr, wp, cr, cp = generate_world(world_index, source_dir_name)
        world_raw_total += wr
        world_packed_total += wp
        collision_raw_total += cr
        collision_packed_total += cp
        print(
            f"world {world_index}: data {wr}->{wp}, "
            f"collisions {cr}->{cp}"
        )

    master = OUTPUT_ROOT / "world_collisions.inc"
    master.write_text(
        "// Generated by generate_world_data.py; do not edit.\n"
        + "".join(
            f"{{$i worlds/world_{index:02d}_collisions.inc}}\n"
            for index in range(len(WORLD_DIRS))
        )
    )
    print(f"world data total: {world_raw_total}->{world_packed_total}")
    print(f"collision total: {collision_raw_total}->{collision_packed_total}")
    print(f"wrote {master}")


if __name__ == "__main__":
    main()
