#!/usr/bin/env python3
"""
Generate STE planar bitmap4 world selector icons from original icon.gif files.

The source GIFs are 96x40 indexed images. Output uses raw ST-low interleaved
bitplane layout, so it can be copied directly with BlitterCopyBitmap4.
"""

from __future__ import annotations

from pathlib import Path
from PIL import Image

FLOB_SRC = Path("/Users/kriss/GCC.ELF/flob")
FLOB_STE = Path("/Users/kriss/GCC.ELF/flob-ste")
WORLDS_SRC = FLOB_SRC / "worlds"
OUT = FLOB_STE / "assets" / "world_icons.inc"

WORLD_DIRS = [
    "00_Escape_From_The_Lab",
    "01_Abominable_Sewers",
    "02_Suburbian_Parkour",
    "03_Hazardous_Mudlands",
    "04_Silver_Dust_Mines",
    "05_Return_To_The_Lab",
]

SRC_ICON_W = 96
SRC_ICON_H = 40
ICON_SCALE = 2
ICON_W = SRC_ICON_W * ICON_SCALE
ICON_H = SRC_ICON_H * ICON_SCALE


def ste_word_from_rgb(r: int, g: int, b: int) -> int:
    rr = (r * 7 + 127) // 255
    gg = (g * 7 + 127) // 255
    bb = (b * 7 + 127) // 255
    return (rr << 8) | (gg << 4) | bb


def luminance(r: int, g: int, b: int) -> int:
    return r * 299 + g * 587 + b * 114  # standard Rec.601, no division needed for sorting


def normalize_palette(palette: list[int], pixels: list[int], n: int = 4) -> tuple[list[int], list[int]]:
    """Sort the first n palette entries darkest→brightest and remap pixel indices."""
    entries = [(i, palette[i * 3], palette[i * 3 + 1], palette[i * 3 + 2]) for i in range(n)]
    sorted_entries = sorted(entries, key=lambda e: luminance(e[1], e[2], e[3]))
    remap = {old_idx: new_idx for new_idx, (old_idx, *_) in enumerate(sorted_entries)}
    new_palette = list(palette)
    for new_idx, (_, r, g, b) in enumerate(sorted_entries):
        new_palette[new_idx * 3]     = r
        new_palette[new_idx * 3 + 1] = g
        new_palette[new_idx * 3 + 2] = b
    new_pixels = [remap.get(p & (n - 1), p & (n - 1)) if p < n else p for p in pixels]
    return new_palette, new_pixels


def gif_palette_words(path: Path, palette_override: list[int] | None = None) -> list[int]:
    im = Image.open(path)
    palette = palette_override if palette_override is not None else (im.getpalette() or [])
    words: list[int] = []
    for i in range(16):
        base = i * 3
        if base + 2 < len(palette):
            words.append(ste_word_from_rgb(palette[base], palette[base + 1], palette[base + 2]))
        else:
            words.append(0)
    return words


def gif_to_st_bitmap4(path: Path) -> tuple[bytes, list[int]]:
    """Returns (bitmap_bytes, normalized_palette_rgb)."""
    im = Image.open(path)
    if im.mode != "P":
        im = im.convert("P")
    if im.size != (SRC_ICON_W, SRC_ICON_H):
        raise RuntimeError(f"{path}: expected {SRC_ICON_W}x{SRC_ICON_H}, got {im.size}")

    im = im.resize((ICON_W, ICON_H), Image.Resampling.NEAREST)

    raw_palette = im.getpalette() or []
    pixels = list(im.getdata())
    palette, pixels = normalize_palette(raw_palette, pixels, n=4)
    out = bytearray()
    for y in range(ICON_H):
        row = pixels[y * ICON_W : (y + 1) * ICON_W]
        for block_x in range(0, ICON_W, 16):
            for plane in range(4):
                word = 0
                for bit in range(16):
                    color = row[block_x + bit] & 15
                    if color & (1 << plane):
                        word |= 1 << (15 - bit)
                out.append((word >> 8) & 255)
                out.append(word & 255)
    return bytes(out), palette


def byte_array(name: str, data: bytes) -> str:
    vals = [f"${b:02X}" for b in data]
    rows = []
    for i in range(0, len(vals), 16):
        rows.append("    " + ",".join(vals[i : i + 16]))
    return f"const {name}: array[0..{len(data) - 1}] of byte = (\n" + ",\n".join(rows) + "\n);\n"


def word_array(name: str, data: list[int]) -> str:
    vals = [f"${w:03X}" for w in data]
    rows = []
    for i in range(0, len(vals), 8):
        rows.append("    " + ",".join(vals[i : i + 8]))
    return f"const {name}: array[0..{len(data) - 1}] of word = (\n" + ",\n".join(rows) + "\n);\n"


def main() -> None:
    icon_paths = [WORLDS_SRC / world_dir / "images" / "icon.gif" for world_dir in WORLD_DIRS]
    chunks = [
        "// Generated by generate_world_icons.py from flob/worlds/*/images/icon.gif",
        f"const WORLD_ICON_WIDTH = {ICON_W};",
        f"const WORLD_ICON_HEIGHT = {ICON_H};",
        "",
    ]
    # Convert bitmaps first — normalize_palette runs inside gif_to_st_bitmap4
    # and returns the corrected palette alongside the bitmap bytes.
    pal_names: list[str] = []
    names: list[str] = []
    for idx, icon_path in enumerate(icon_paths):
        bitmap, norm_palette = gif_to_st_bitmap4(icon_path)

        pal_name = f"WORLD_ICON_PAL_{idx:02d}"
        pal_names.append(pal_name)
        chunks.append(word_array(pal_name, gif_palette_words(icon_path, palette_override=norm_palette)))

        const_name = f"WORLD_ICON_{idx:02d}"
        names.append(const_name)
        chunks.append(byte_array(const_name, bitmap))

    # Pointer array to per-world palettes
    chunks.append(f"const WORLD_ICON_PAL_PTRS: array[0..{len(pal_names) - 1}] of pointer = (")
    for idx, name in enumerate(pal_names):
        comma = "," if idx < len(pal_names) - 1 else ""
        chunks.append(f"    @{name}[0]{comma}")
    chunks.append(");\n")

    chunks.append(f"const WORLD_ICON_PTRS: array[0..{len(names) - 1}] of pointer = (")
    for idx, name in enumerate(names):
        comma = "," if idx < len(names) - 1 else ""
        chunks.append(f"    @{name}[0]{comma}")
    chunks.append(");")
    chunks.append("")

    OUT.write_text("\n".join(chunks))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
