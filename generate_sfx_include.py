#!/usr/bin/env python3
"""Generate Pascal byte arrays from the Atari STE signed 8-bit SFX files."""

from pathlib import Path


ROOT = Path(__file__).resolve().parent
RAW_DIR = ROOT / "audio" / "ste_sfx_wav"
OUTPUT = ROOT / "assets" / "sfx_raw.inc"

EFFECTS = (
    "flip",
    "slime_pick",
    "dead",
    "pick_all",
    "pick_goal",
    "reveal",
    "big_slime",
    "console",
    "water_drop",
    "lever",
    "siren",
    "circuit",
    "gear",
    "valve",
    "bell",
    "gas",
    "insect",
)


def pascal_name(name: str) -> str:
    return "SFX_" + name.upper() + "_RAW_DATA"


def format_array(name: str, data: bytes) -> str:
    lines = [f"const {pascal_name(name)}: array[0..{len(data) - 1}] of byte = ("]
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        suffix = "," if offset + len(chunk) < len(data) else ""
        lines.append("    " + ",".join(f"${value:02X}" for value in chunk) + suffix)
    lines.append(");")
    return "\n".join(lines)


def main() -> None:
    sections = ["{ generated by generate_sfx_include.py; do not edit }", ""]
    total = 0
    for name in EFFECTS:
        path = RAW_DIR / f"{name}.raw"
        if not path.is_file():
            raise SystemExit(f"Missing SFX input: {path}; run 'make sfx-wav' first")
        data = path.read_bytes()
        if not data:
            raise SystemExit(f"Empty SFX input: {path}")
        sections.append(format_array(name, data))
        sections.append("")
        total += len(data)
    OUTPUT.write_text("\n".join(sections), encoding="ascii")
    print(f"Generated {OUTPUT} ({len(EFFECTS)} samples, {total} bytes)")


if __name__ == "__main__":
    main()
