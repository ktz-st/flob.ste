#!/usr/bin/env python3
"""Extract compact 50 Hz POKEY and preconverted PSG streams for STE SFX."""

from __future__ import annotations

import subprocess
import tempfile
from pathlib import Path

import extract_a8_sfx as source


ROOT = Path(__file__).resolve().parent
A8_ROOT = ROOT.parent / "flob"
OUTPUT = ROOT / "assets" / "sfx_synth.inc"
SILENT_TAIL_FRAMES = 5
POKEY_PAL_CLOCK = 1_773_447.0
YM_CLOCK = 8_010_613.0 / 4.0
YM_VOLUME = (0, 7, 9, 10, 11, 12, 12, 13, 13, 14, 14, 14, 15, 15, 15, 15)


def pascal_name(name: str, suffix: str) -> str:
    return "SFX_" + name.upper() + suffix


def scan_effect(module: bytes, player: bytes, name: str, value: int) -> list[tuple[int, int]]:
    sap = source.make_sap(module, player, value + 0x10, name)
    marker = sap.index(b"\xff\xff")
    sap = (
        sap[:marker].replace(b"\r\n\r\n", b"\r\nTIME 00:04.000\r\n\r\n")
        + sap[marker:]
    )

    with tempfile.NamedTemporaryFile(suffix=".sap") as temp:
        Path(temp.name).write_bytes(sap)
        dump = subprocess.check_output(("asapscan", "-d", temp.name), text=True)

    frames: list[tuple[int, int]] = []
    for line in dump.splitlines():
        if ":" not in line or "|" not in line:
            continue
        registers = line.split(":", 1)[1]
        left_text, right_text = registers.split("|", 1)
        left = [int(token, 16) for token in left_text.split()]
        right = [int(token, 16) for token in right_text.split()]
        if len(left) != 9 or len(right) != 9:
            continue
        if left[0] != right[0] or left[8] != 0 or right[8] != 0:
            raise ValueError(f"Unsupported stereo frequency or AUDCTL in {name}: {line}")
        if any(left[index] & 15 for index in (3, 5, 7)) or any(
            right[index] & 15 for index in (3, 5, 7)
        ):
            raise ValueError(f"More than one active POKEY voice in {name}: {line}")

        left_audc = left[1]
        right_audc = right[1]
        if (left_audc & 0xF0) != (right_audc & 0xF0):
            raise ValueError(f"Different stereo distortions in {name}: {line}")
        volume = ((left_audc & 15) + (right_audc & 15) + 1) // 2
        frames.append((left[0], (left_audc & 0xF0) | volume))

    active = [index for index, (_, audc) in enumerate(frames) if audc & 15]
    if not active:
        raise ValueError(f"No audible frames extracted for {name}")
    return frames[: min(len(frames), active[-1] + 1 + SILENT_TAIL_FRAMES)]


def encode_pokey_runs(frames: list[tuple[int, int]]) -> bytes:
    encoded = bytearray()
    index = 0
    while index < len(frames):
        audf, audc = frames[index]
        run = 1
        while index + run < len(frames) and frames[index + run] == (audf, audc) and run < 255:
            run += 1
        encoded.extend((run, audf, audc))
        index += run
    return bytes(encoded)


def convert_psg_frame(audf: int, audc: int) -> tuple[int, int, int, int, int]:
    frequency = POKEY_PAL_CLOCK / (2.0 * 28.0 * (audf + 1))
    period = max(1, min(4095, round(YM_CLOCK / (16.0 * frequency))))
    distortion = audc & 0xF0
    if distortion == 0xA0:
        mixer = 0x20
    elif distortion == 0x20:
        mixer = 0x00
    else:
        mixer = 0x04
    noise = max(1, min(31, period >> 5))
    return period & 0xFF, (period >> 8) & 15, noise, mixer, YM_VOLUME[audc & 15]


def encode_psg_runs(frames: list[tuple[int, int]]) -> bytes:
    converted = [convert_psg_frame(audf, audc) for audf, audc in frames]
    encoded = bytearray()
    index = 0
    while index < len(converted):
        frame = converted[index]
        run = 1
        while index + run < len(converted) and converted[index + run] == frame and run < 255:
            run += 1
        encoded.extend((run, *frame))
        index += run
    return bytes(encoded)


def format_array(constant: str, data: bytes) -> str:
    lines = [f"const {constant}: array[0..{len(data) - 1}] of byte = ("]
    for offset in range(0, len(data), 15):
        chunk = data[offset : offset + 15]
        suffix = "," if offset + len(chunk) < len(data) else ""
        lines.append("    " + ",".join(f"${value:02X}" for value in chunk) + suffix)
    lines.append(");")
    return "\n".join(lines)


def main() -> None:
    asapscan = subprocess.run(("asapscan", "-v"), capture_output=True)
    if asapscan.returncode != 0:
        raise SystemExit("asapscan not found in PATH")

    module_path = sorted((A8_ROOT / "worlds").glob("*/_flob_ingame.rmt"))[0]
    module = source.find_segment(module_path, source.RMT_MODULE_ADDRESS)
    player = source.find_segment(A8_ROOT / "flob.xex", source.RMT_PLAYER_START, source.RMT_PLAYER_END)

    sections = ["{ generated by generate_sfx_synth.py; do not edit }", ""]
    total_frames = 0
    total_pokey_bytes = 0
    total_psg_bytes = 0
    for name, value in source.EFFECTS:
        frames = scan_effect(module, player, name, value)
        pokey_stream = encode_pokey_runs(frames)
        psg_stream = encode_psg_runs(frames)
        sections.append(format_array(pascal_name(name, "_SYNTH_DATA"), pokey_stream))
        sections.append("")
        sections.append(format_array(pascal_name(name, "_PSG_DATA"), psg_stream))
        sections.append("")
        total_frames += len(frames)
        total_pokey_bytes += len(pokey_stream)
        total_psg_bytes += len(psg_stream)
        print(
            f"{name:12s} {len(frames):3d} frames -> "
            f"{len(pokey_stream):3d} POKEY, {len(psg_stream):3d} PSG bytes"
        )

    OUTPUT.write_text("\n".join(sections), encoding="ascii")
    print(
        f"Generated {OUTPUT}: {total_frames} frames, "
        f"{total_pokey_bytes} POKEY + {total_psg_bytes} PSG bytes"
    )


if __name__ == "__main__":
    main()
