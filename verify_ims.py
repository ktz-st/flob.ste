"""All generated frames: real Hatari pixel comparison and isolated blit timing."""
import os
from pathlib import Path
import re
import subprocess
import tempfile
import time

ROOT=Path(__file__).resolve().parent


def main():
    entries=[]
    frames=0
    for path in sorted((ROOT/'generated/sprite_assets_atlas').glob('*.inc')):
        name=path.stem.upper()
        count=int(re.search(r'_FRAME_COUNT = (\d+)',path.read_text())[1])
        frames+=count
        entries.append(f'    (frames:@SPR_{name}_FRAMES[0]; words:@SPR_{name}_WORDS[0]; count:{count})')
    (ROOT/'generated/ims_test_catalog.inc').write_text(
        '// Generated by verify_ims.py; test build only.\n'
        +f'const IMSTestSprites: array[0..{len(entries)-1}] of TIMSTestSprite = (\n'
        +',\n'.join(entries)+'\n);\n')
    subprocess.run(['make','ims.o','ems.o'],cwd=ROOT,check=True)
    with tempfile.TemporaryDirectory(prefix='flob-ims-') as directory:
        directory=Path(directory)
        program=directory/'VERIFY.PRG'
        subprocess.run(['/opt/fpc/lib/fpc/3.3.1/ppcross68k','-Tatari','-O2','-Si','-Xs',
            '-dSTE','-dNO_EMS','-dVERIFY_IMS','-vw','-vm','-vi',f'-o{program}','flob.pas'],cwd=ROOT,check=True)
        cmd=[str(ROOT.parent/'hatariB/hatari/build-headless/src/hatari'),
            '--machine','ste','--memsize','4','--cpulevel','0','--cpuclock','8',
            '--monitor','rgb','--tos',str(ROOT.parent/'hatariB/emutos/etos1024k.img'),
            '--fast-boot','true','--fast-forward','true','--frameskips','0','--sound','off',
            '--joy0','none','--joy1','none','--confirm-quit','false','--run-vbls','1000000',
            '--benchmark',str(program)]
        result=''
        with (ROOT/'reports/ims_verification.log').open('w') as log:
            process=subprocess.Popen(cmd,stdout=log,stderr=subprocess.STDOUT,
                env=dict(os.environ,SDL_VIDEODRIVER='dummy',SDL_AUDIODRIVER='dummy'))
            try:
                deadline=time.monotonic()+240
                while time.monotonic()<deadline:
                    path=directory/'IMS.TXT'
                    if path.exists(): result=path.read_text()
                    if 'BENCH draws=' in result or 'FAIL' in result: break
                    if process.poll() is not None: break
                    time.sleep(.5)
            finally:
                if process.poll() is None:
                    process.terminate()
                    try: process.wait(timeout=3)
                    except subprocess.TimeoutExpired:
                        process.kill(); process.wait()
    (ROOT/'reports/ims_verification.txt').write_text(result)
    assert f'PASS comparisons={frames*20} actual_ims_calls={frames*17}' in result, result[-2000:]
    match=re.search(r'BENCH draws=(\d+) pascal_ticks=(\d+) asm_ticks=(\d+)',result)
    assert match, result[-2000:]
    draws,old,new=map(int,match.groups())
    summary=(f'{len(entries)} sprites, {frames} frames, {frames*20} comparisons.\n'
        f'{draws} draws per timing pass: Pascal {old*5} ms, ASM {new*5} ms; '
        f'{100*(old-new)/old:.1f}% less time.\n'
        'STE 8 MHz, EmuTOS, Hatari. Emulated HZ200 time. Not gameplay FPS.\n')
    (ROOT/'reports/ims_benchmark.txt').write_text(summary)
    print(summary)


if __name__=='__main__': main()
