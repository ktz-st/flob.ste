"""Generate a small EMX-style blitter program from the canonical build's slime masks.

Not the AGT file format: retain our planar colour data, clipping and cdecl ABI.
All shifts are supported. Identical mask programs share code across frames.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def main():
    source = (ROOT / 'generated/sprite_assets_atlas/slime.inc').read_text()
    frames = [dict((k, int(v)) for k, v in re.findall(r'(\w+):(\d+)', record))
              for record in re.findall(r'\((widthPx:.*?)\)', source)]
    section = source.split('const SPR_SLIME_WORDS', 1)[1].split(');', 1)[0]
    words = [int(v, 16) for v in re.findall(r'\$([0-9A-Fa-f]+)', section)]
    table = {}
    programs = {}
    for frame in frames:
        assert frame['rowWords'] == 1 and 0 < frame['widthPx'] <= 16
        assert frame['heightPx'] >= 2
        masks = words[frame['maskOffset']:frame['dataOffset']]
        assert len(masks) == frame['heightPx']
        for shift in range(16):
            pairs = tuple((((~m & 65535) << 16) >> shift) for m in masks)
            count = (shift + frame['widthPx'] + 15) // 16
            key = (shift, count, pairs)
            if key not in programs:
                programs[key] = f'emx_{len(programs)}'
            offset = frame['paletteOffset'] + shift * 4
            assert offset not in table and offset % 4 == 0 and offset < 32768
            table[offset] = programs[key]
    lines = ['; Generated by generate_slime_emx.py; do not edit.',
             '        export DrawSlimeEMX', '        export _DrawSlimeEMX',
             '; cdecl: gfx, destination, dispatch byte offset (all 32 bits).',
             'DrawSlimeEMX:', '_DrawSlimeEMX:',
             '        movem.l d2/a2-a3,-(sp)',
             '        movea.l 16(sp),a0', '        movea.l 20(sp),a1',
             '        move.l 24(sp),d0', '        lea emx_table(pc),a2',
             '        movea.l (a2,d0.w),a2', '        lea $ffff8a20.w,a3',
             '.wait:', '        btst #7,28(a3)', '        bne.s .wait',
             '        move.w #8,(a3)', '        move.w #2,2(a3)',
             '        move.l a0,4(a3)', '        move.w #$ffff,10(a3)',
             '        move.w #8,14(a3)', '        move.w #$0203,26(a3)',
             '        moveq #4,d2', '        jsr (a2)',
             '        movem.l (sp)+,d2/a2-a3', '        rts',
             '        even', 'emx_table:']
    for offset in range(0, max(table) + 4, 4):
        lines.append(f'        dc.l {table.get(offset, "0")}')
    for (shift, count, pairs), label in programs.items():
        lines += [label + ':', f'        move.w #{count},22(a3)',
                  f'        move.w #{2 - (count - 1) * 8},16(a3)',
                  f'        move.b #${(shift | (64 if count > 1 else 0)):02x},29(a3)']
        previous = None
        for row, pair in enumerate(pairs):
            mask1, mask3 = pair >> 16, pair & 65535
            if previous is None or previous[0] != mask1:
                lines.append(f'        move.w #${mask1:04x},8(a3)')
            if previous is None or previous[1] != mask3:
                lines.append(f'        move.w #${mask3:04x},12(a3)')
            lines += ['        move.l a1,18(a3)', '        move.w d2,24(a3)',
                      '        move.b #$c0,28(a3)', f'.busy{row}:',
                      '        btst #7,28(a3)', f'        bne.s .busy{row}']
            if row + 1 < len(pairs):
                lines.append('        lea 160(a1),a1')
            previous = mask1, mask3
        lines.append('        rts')
    (ROOT / 'generated/slime_emx.s').write_text('\n'.join(lines) + '\n')
    print(f'{len(frames)} frames, {len(table)} entries, {len(programs)} shared programs, '
          f'{max(table) + 4} table bytes')


if __name__ == '__main__':
    main()
