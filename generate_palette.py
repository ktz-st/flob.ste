#!/usr/bin/env python3
"""Convert the verified Atari PAL RGB reference palette to Atari STE words."""

from __future__ import annotations

from pathlib import Path


ROOT = Path(__file__).resolve().parent
RGB_SOURCE = ROOT / "assets" / "a8_pal_rgb.hex"
RGB_OUTPUT = ROOT / "generated" / "a8-pal-rgb.pal"
PASCAL_OUTPUT = ROOT / "palette.inc"

# STE stores RGB bit 0 in bit 3 of each component nibble.
STE_NIBBLE = (
    0x0, 0x8, 0x1, 0x9, 0x2, 0xA, 0x3, 0xB,
    0x4, 0xC, 0x5, 0xD, 0x6, 0xE, 0x7, 0xF,
)


def load_rgb() -> list[tuple[int, int, int]]:
    raw = bytes.fromhex(RGB_SOURCE.read_text(encoding="ascii"))
    if len(raw) != 256 * 3:
        raise ValueError(f"{RGB_SOURCE} must contain exactly 256 RGB colours")
    return [tuple(raw[offset:offset + 3]) for offset in range(0, len(raw), 3)]


def rgb_to_ste(red: int, green: int, blue: int) -> int:
    def component(value: int) -> int:
        level = (value * 15 + 127) // 255
        return STE_NIBBLE[level]

    return (component(red) << 8) | (component(green) << 4) | component(blue)


def write_pascal(palette: list[tuple[int, int, int]]) -> None:
    words = [rgb_to_ste(*rgb) for rgb in palette]
    lines = [
        "{ Generated by generate_palette.py from the verified Atari PAL palette. }",
        "const",
        "    STE_PAL: array[0..255] of word =",
        "    (",
    ]
    for start in range(0, 256, 8):
        values = ", ".join(f"${word:03X}" for word in words[start:start + 8])
        comma = "," if start < 248 else ""
        lines.append(f"    {{ ${start:02X}-${start + 7:02X} }} {values}{comma}")
    lines.extend(("    );", ""))
    PASCAL_OUTPUT.write_text("\n".join(lines), encoding="ascii")


def main() -> None:
    palette = load_rgb()
    RGB_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    RGB_OUTPUT.write_bytes(bytes(component for rgb in palette for component in rgb))
    write_pascal(palette)


if __name__ == "__main__":
    main()
